const { chromium } = require('playwright');
const { FakeGitHub } = require('./fakegh');
const gh = new FakeGitHub();
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext();
  let off = false;
  await ctx.route('https://api.github.com/**', r => (off ? r.abort('internetdisconnected') : gh.handle(r)));
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.goto('http://localhost:8765/');
  await p.fill('[name=token]', 'good-token'); await p.fill('[name=pw]', 'quiet river lamp'); await p.fill('[name=pw2]', 'quiet river lamp');
  await p.click('#setupForm [type=submit]');
  await p.waitForSelector('.welcome', { timeout: 20000 });
  await p.click('[data-act=suggest] >> nth=0');
  await p.waitForSelector('.tile');
  await p.waitForFunction(() => navigator.serviceWorker.controller || navigator.serviceWorker.ready.then(() => true));
  await p.reload(); await p.waitForSelector('.tile');
  console.log('SW controlling:', await p.evaluate(() => !!navigator.serviceWorker.controller));
  off = true; await ctx.setOffline(true);
  await p.reload(); await p.waitForSelector('.tile', { timeout: 10000 });
  await p.click('.btn-plus');
  await p.waitForFunction(() => window.tally.status.state === 'offline');
  console.log('offline open + log OK, pill:', (await p.textContent('#syncPill')).trim());
  off = false; await ctx.setOffline(false);
  await p.evaluate(() => window.tally.sync());
  await p.waitForFunction(() => window.tally.status.state === 'ok' && !window.tally.pending.length);
  console.log('back online synced OK; errors:', errs);
  await b.close();
})().catch(e => { console.error('FAIL', e.message); process.exit(1); });
